"""Bounded, non-destructive scanning through the stock tuning routine.

No station-list writer is called. A 100 ms native tick schedules settling and
station dwell; station acceptance requires tune completion, lock and C/N.
"""
from lcd_draw import Asm
from bandwidth_patch import farcall
from native_ui import Screen
import native_features as n

THRESHOLDS=(4,8,12,16)
DWELL_TICKS=(20,50,100)


def scan_control(base=0x1800,state=n.STATE):
    a=Asm(base)
    for label in ('open','poll','message'):n.jump(a,label)
    def get(field):n.read(a,state+field)
    def put(field,value):n.write(a,state+field,value)
    def load(field):
        get(field);a.emit(0xFA,0xA3,0xE0,0xFB)
    def store(field):
        a.movdptr(state+field);a.movar(2);a.movxda();a.emit(0xA3);a.movar(3);a.movxda()
    def constant(field,value):put(field,value&255);put(field+1,value>>8)
    def cmp(field):
        get(field);a.emit(0xFC,0xA3,0xE0,0xFD);a.movar(2);a.emit(0xC3,0x9C);a.movar(3);a.emit(0x9D)
    def finish():n.restore_context(a);a.emit(0x02,0x01,0x00)
    def dirty():put(n.DIRTY,1)
    def jz(label):a.emit(0x70,3);n.jump(a,label)
    def jnz(label):a.emit(0x60,3);n.jump(a,label)
    def cjne(value,label):a.emit(0xB4,value,2,0x80,3);n.jump(a,label)
    def consume():put(n.ACTION,7);n.jump(a,'message_done')
    def stop():put(n.SCAN_STATUS,0)

    a.L('open');n.save_context(a);stop()
    a.movri(0,0x18);a.emit(0xE6);a.movdptr(state+n.SCAN_MODE);a.movxda()
    a.lcall('anchor');a.lcall('limits');dirty();finish()
    a.L('anchor');n.read(a,0x3CDC);a.emit(0xFA,0xA3,0xE0,0xFB);store(n.SCAN_START);a.ret()

    a.L('limits')
    get(n.SCAN_MODE);a.cjne_ai(1,'limits_am')
    constant(116,300);constant(118,2300);put(n.SCAN_STEP,1);a.sjmp('choose_range')
    a.L('limits_am');a.cjne_ai(2,'limits_sw')
    a.movri(0,0x8B);a.emit(0xE6);a.jz('limits_mw9')
    constant(116,520);constant(118,1710);put(n.SCAN_STEP,10);a.sjmp('choose_range')
    a.L('limits_mw9');constant(116,522);constant(118,1710);put(n.SCAN_STEP,9);a.sjmp('choose_range')
    a.L('limits_sw');constant(116,150);constant(118,30000);put(n.SCAN_STEP,5)
    a.L('choose_range');get(n.SCAN_RANGE);a.cjne_ai(0,'range_not_default')
    get(n.SCAN_MODE);a.cjne_ai(1,'default_am');constant(n.SCAN_LOW,870);constant(n.SCAN_HIGH,1080);n.jump(a,'align')
    a.L('default_am');a.cjne_ai(3,'range_full');constant(n.SCAN_LOW,4750);constant(n.SCAN_HIGH,21850);n.jump(a,'align')
    a.L('range_not_default');a.cjne_ai(3,'range_window')
    a.L('range_full');load(116);store(n.SCAN_LOW);load(118);store(n.SCAN_HIGH);n.jump(a,'align')
    a.L('range_window');get(n.SCAN_RANGE);a.cjne_ai(1,'span_wide');a.movri(6,100);a.movri(7,0);a.sjmp('span_mode')
    a.L('span_wide');a.movri(6,244);a.movri(7,1)
    a.L('span_mode');get(n.SCAN_MODE);a.cjne_ai(1,'span_ready')
    get(n.SCAN_RANGE);a.cjne_ai(1,'span_fm_wide');a.movri(6,10);a.sjmp('span_fm_done')
    a.L('span_fm_wide');a.movri(6,50)
    a.L('span_fm_done');a.movri(7,0)
    a.L('span_ready');load(n.SCAN_START);a.movar(2);a.emit(0xC3,0x9E,0xFA);a.movar(3);a.emit(0x9F,0xFB)
    a.jnc('low_no_underflow');a.lcall('absolute_low');a.sjmp('low_ready')
    a.L('low_no_underflow');cmp(116);a.jnc('low_ready');a.lcall('absolute_low')
    a.L('low_ready');store(n.SCAN_LOW)
    load(n.SCAN_START);a.movar(2);a.emit(0x2E,0xFA);a.movar(3);a.emit(0x3F,0xFB)
    a.jnc('high_no_overflow');a.lcall('absolute_high');a.sjmp('high_ready')
    a.L('high_no_overflow');cmp(118);a.emit(0x40);a._rel('high_ready');a.lcall('absolute_high')
    a.L('high_ready');store(n.SCAN_HIGH)
    a.L('align')
    load(n.SCAN_LOW);cmp(118);a.emit(0x40);a._rel('low_max_ok');a.lcall('absolute_high')
    a.L('low_max_ok');store(n.SCAN_LOW)
    load(n.SCAN_HIGH);cmp(116);a.jnc('high_min_ok');a.lcall('absolute_low')
    a.L('high_min_ok');store(n.SCAN_HIGH)
    load(n.SCAN_LOW);get(n.SCAN_STEP);a.emit(0xFC);a.lcall('remainder');a.movar(5);a.jz('align_high')
    a.movar(4);a.emit(0xC3,0x9D,0xFD);load(n.SCAN_LOW);a.movar(2);a.emit(0x2D,0xFA);a.movar(3);a.emit(0x34,0,0xFB);store(n.SCAN_LOW)
    a.L('align_high');load(n.SCAN_HIGH);get(n.SCAN_STEP);a.emit(0xFC);a.lcall('remainder')
    load(n.SCAN_HIGH);a.movar(2);a.emit(0xC3,0x9D,0xFA);a.movar(3);a.emit(0x94,0,0xFB);store(n.SCAN_HIGH);a.ret()
    a.L('absolute_low');load(116);a.ret()
    a.L('absolute_high');load(118);a.ret()
    a.L('remainder');a.movri(5,0);a.movri(0,16)
    a.L('divide_bit');a.clr(0xD7);a.movar(2);a.emit(0x33,0xFA);a.movar(3);a.emit(0x33,0xFB)
    a.movar(5);a.emit(0x33,0xC3,0x9C);a.jnc('mod_keep');a.emit(0x2C)
    a.L('mod_keep');a.emit(0xFD);a.djnz(0,'divide_bit');a.ret()

    a.L('start')
    # Start from the current channel if it is inside the selected range.
    n.read(a,0x3CDC);a.emit(0xFA,0xA3,0xE0,0xFB);cmp(n.SCAN_LOW);a.jnc('start_check_high');a.sjmp('restart')
    a.L('start_check_high');cmp(n.SCAN_HIGH);a.emit(0x40);a._rel('start_current');a.movar(2);a.emit(0x6C);jnz('restart');a.movar(3);a.emit(0x6D);jnz('restart')
    # Round a current off-grid numeric entry down, then clamp to the range.
    load_current='start_current'
    a.L(load_current);n.read(a,0x3CDC);a.emit(0xFA,0xA3,0xE0,0xFB);get(n.SCAN_STEP);a.emit(0xFC);a.lcall('remainder')
    n.read(a,0x3CDC);a.emit(0xFA,0xA3,0xE0,0xFB);a.movar(2);a.emit(0xC3,0x9D,0xFA);a.movar(3);a.emit(0x94,0,0xFB)
    cmp(n.SCAN_LOW);a.jnc('tune');a.sjmp('restart')
    a.L('restart');get(n.SCAN_DIRECTION);a.jz('restart_down');load(n.SCAN_LOW);a.sjmp('tune')
    a.L('restart_down');load(n.SCAN_HIGH)
    a.L('tune')
    cmp(n.SCAN_LOW);a.jnc('tune_low_ok');load(n.SCAN_LOW)
    a.L('tune_low_ok');cmp(n.SCAN_HIGH);a.emit(0x40);a._rel('tune_high_ok');load(n.SCAN_HIGH)
    a.L('tune_high_ok')
    a.movdptr(0x3CDC);a.movar(2);a.movxda();a.emit(0xA3);a.movar(3);a.movxda()
    a.movri(6,0)  # IAR native leaf-call zero register
    farcall(a,0x1D,0x198B)
    put(n.SCAN_STATUS,1);put(n.SCAN_WAIT,2);put(n.SCAN_SETTLE,20)
    n.read(a,0x3AAC);a.movdptr(state+n.SCAN_TICK);a.movxda();dirty();a.ret()
    a.L('advance')
    get(n.SCAN_STEP);a.emit(0xFE);get(n.SCAN_DIRECTION);a.jz('advance_down')
    n.read(a,0x3CDC);a.emit(0x2E,0xFA,0xA3,0xE0,0x34,0,0xFB)
    cmp(n.SCAN_HIGH);a.emit(0x40);a._rel('advance_tune');a.movar(2);a.emit(0x6C);jnz('scan_end');a.movar(3);a.emit(0x6D);jnz('scan_end');a.sjmp('advance_tune')
    a.L('advance_down');n.read(a,0x3CDC);a.emit(0xC3,0x9E,0xFA,0xA3,0xE0,0x94,0,0xFB)
    a.jnc('advance_compare_low');a.sjmp('scan_end')
    a.L('advance_compare_low');cmp(n.SCAN_LOW);a.emit(0x40);a._rel('scan_end')
    a.L('advance_tune');n.jump(a,'tune')
    a.L('scan_end');put(n.SCAN_STATUS,4);dirty();a.ret()

    a.L('poll');n.save_context(a)
    # The caller also checks these guards; keep the service safe independently.
    n.read(a,0x3AB8);cjne(3,'poll_stop');n.read(a,0x3CD0);jnz('poll_stop')
    a.movri(0,0x18);a.emit(0xE6,0xFA);get(n.SCAN_MODE);a.emit(0x6A);jnz('poll_stop')
    get(n.SCAN_STATUS);a.cjne_ai(1,'poll_found_check');a.sjmp('poll_tick')
    a.L('poll_found_check');cjne(3,'poll_done_jump')
    a.L('poll_tick')
    n.read(a,0x3AAC);a.emit(0xFA);get(n.SCAN_TICK);a.emit(0xFB);a.movar(2);a.emit(0xC3,0x9B)
    a.jnc('elapsed');a.emit(0x24,10)
    a.L('elapsed');a.emit(0xFE);jz('poll_done_jump')
    a.movar(2);a.movdptr(state+n.SCAN_TICK);a.movxda()
    get(n.SCAN_STATUS);a.cjne_ai(3,'poll_settle')
    get(n.SCAN_REMAIN);a.emit(0xC3,0x9E);a.jnc('dwell_remaining');a.movai(0)
    a.L('dwell_remaining');a.movxda();a.jz('poll_advance');n.jump(a,'poll_done_jump')
    a.L('poll_settle');get(n.SCAN_SETTLE);a.emit(0xC3,0x9E);a.jnc('settle_remaining');a.movai(0)
    a.L('settle_remaining');a.movxda()
    get(n.SCAN_WAIT);a.emit(0xC3,0x9E);a.jnc('wait_remaining');a.movai(0)
    a.L('wait_remaining');a.movxda();jnz('poll_done_jump')
    a.movri(1,20);a.movri(2,4);farcall(a,0x1D,0x1D3E)
    a.movar(2);a.anlai(0x40);a.jz('not_complete')
    a.movar(2);a.anlai(0x20);a.jz('poll_advance')
    get(n.SCAN_MODE);a.cjne_ai(1,'scan_am_cn');a.movar(5);a.sjmp('scan_cn_ready')
    a.L('scan_am_cn');a.movar(4)
    a.L('scan_cn_ready');a.anlai(127);a.movdptr(state+n.SCAN_CN);a.movxda();a.emit(0xFA)
    get(n.SCAN_THRESHOLD);a.movdptr(0);threshold_patch=len(a.code)-2;a.emit(0x93,0xFB)
    a.movar(2);a.emit(0xC3,0x9B);a.emit(0x40);a._rel('poll_advance')
    put(n.SCAN_STATUS,3);get(n.SCAN_DWELL);a.movdptr(0);dwell_patch=len(a.code)-2;a.emit(0x93)
    a.movdptr(state+n.SCAN_REMAIN);a.movxda();dirty();n.jump(a,'poll_done_jump')
    a.L('not_complete');get(n.SCAN_SETTLE);a.jz('poll_advance');put(n.SCAN_WAIT,1);n.jump(a,'poll_done_jump')
    a.L('poll_advance');a.lcall('advance');n.jump(a,'poll_done_jump')
    a.L('poll_stop');stop();get(n.FLAGS);a.anlai(0xC2);a.movxda();dirty()
    a.L('poll_done_jump');n.jump(a,'poll_done')
    a.L('poll_done');finish()

    a.L('message');n.save_context(a)
    n.read(a,0x3AB8);cjne(3,'message_stop');n.read(a,0x3CD0);jnz('message_stop')
    a.movri(0,0x18);a.emit(0xE6,0xFA);get(n.SCAN_MODE);a.emit(0x6A);jnz('message_stop')
    a.movri(0,0x8C);a.emit(0xE6);a.jz('scan_unlocked');n.jump(a,'message_done')
    a.L('scan_unlocked');a.movar(1);jz('message_done_jump')
    a.cjne_ai(0xF8,'scan_not_f8');n.jump(a,'message_done_jump')
    a.L('scan_not_f8');a.cjne_ai(0xFE,'scan_keys');n.jump(a,'message_done_jump')
    a.L('scan_keys')
    a.movar(1);a.cjne_ai(n.LONG_SCREEN,'scan_not_sleep')
    put(n.SCAN_STATUS,2);dirty();put(n.ACTION,5);n.jump(a,'message_done')
    a.L('scan_not_sleep');a.cjne_ai(n.LONG_MENU,'scan_short_keys');n.jump(a,'key_settings')
    a.L('scan_short_keys')
    for key,label in [(0x97,'key_range'),(0x98,'key_threshold'),(0x99,'key_dwell'),(0x9A,'key_direction'),
                      (0x9B,'key_start'),(0x9C,'key_next'),(0x9D,'key_restart'),(0x9E,'key_settings'),(0x96,'key_exit')]:
        nxt='scan_key_'+str(key);a.cjne_ai(key,nxt);n.jump(a,label);a.L(nxt)
    a.movar(1);a.emit(0xC3,0x94,0xF8);a.emit(0x40,3);n.jump(a,'message_done_jump')
    a.movar(1);a.anlai(31);a.emit(0xC3,0x94,0x16);a.jnc('key_consume')
    # A stock volume/tuning/mode key leaves scanning before stock dispatch.
    stop();get(n.FLAGS);a.anlai(0xC2);a.movxda();dirty();n.jump(a,'message_done_jump')
    a.L('key_consume');consume()
    a.L('message_done_jump');n.jump(a,'message_done')
    for label,field,modulus in [('key_range',n.SCAN_RANGE,4),('key_threshold',n.SCAN_THRESHOLD,4),
                                ('key_dwell',n.SCAN_DWELL,3),('key_direction',n.SCAN_DIRECTION,2)]:
        a.L(label);stop();get(field);a.emit(0x04);a.cjne_ai(modulus,label+'_store');a.movai(0)
        a.L(label+'_store');a.movxda();put(n.NV_DIRTY,1);put(n.SAVE_TICKS,0)
        if field==n.SCAN_RANGE:a.lcall('anchor');a.lcall('limits')
        dirty();consume()
    a.L('key_start');get(n.SCAN_STATUS);a.cjne_ai(1,'key_start_found');a.sjmp('key_pause')
    a.L('key_start_found');a.cjne_ai(3,'key_start_paused')
    a.L('key_pause');put(n.SCAN_STATUS,2);dirty();consume()
    a.L('key_start_paused');a.cjne_ai(2,'key_start_new');a.lcall('advance');consume()
    a.L('key_start_new');a.cjne_ai(4,'start_not_end');a.lcall('restart');consume()
    a.L('start_not_end');a.lcall('start');consume()
    a.L('key_next');get(n.SCAN_STATUS);a.jz('start_not_end');a.cjne_ai(4,'next_active');a.lcall('restart');consume()
    a.L('next_active');a.lcall('advance');consume()
    a.L('key_restart');a.lcall('restart');consume()
    a.L('key_settings');stop();get(n.FLAGS);a.anlai(0xC2);a.orlai(n.MENU);a.movxda();dirty();consume()
    a.L('key_exit');stop();get(n.FLAGS);a.anlai(0xC2);a.movxda();n.write(a,0x3CD1,1);dirty();consume()
    n.jump(a,'message_done')
    a.L('message_stop');stop();get(n.FLAGS);a.anlai(0xC2);a.movxda();dirty()
    a.L('message_done');finish()
    threshold_pc=a.base+len(a.code);a.code.extend(bytes(THRESHOLDS));dwell_pc=a.base+len(a.code);a.code.extend(bytes(DWELL_TICKS))
    a.code[threshold_patch:threshold_patch+2]=threshold_pc.to_bytes(2,'big');a.code[dwell_patch:dwell_patch+2]=dwell_pc.to_bytes(2,'big')
    code=a.assemble()
    if len(code)>0x800:raise ValueError(f'scan control exceeds bank: {len(code)}')
    return code,a.labels


def scan_renderer(base=0x1800,state=n.STATE):
    ui=Screen(base,state);a=ui.a
    ui.clear();ui.text('SCAN ');ui.mode();ui.text(' ');ui.get(n.SCAN_STATUS)
    for value,text in [(0,'READY'),(1,'RUN'),(2,'PAUSED'),(3,'STATION'),(4,'END')]:
        nxt='status_'+str(value);a.cjne_ai(value,nxt);ui.text(text);n.jump(a,'status_done');a.L(nxt)
    a.L('status_done');ui.row();ui.frequency();ui.text(' C/N:');ui.number(n.CN);ui.flush(0)
    ui.clear();ui.text('1 RANGE:');ui.get(n.SCAN_RANGE)
    for value,text in [(0,'BROADCAST'),(1,'NEAR'),(2,'WIDE'),(3,'FULL')]:
        nxt='range_'+str(value);a.cjne_ai(value,nxt);ui.text(text);n.jump(a,'range_done');a.L(nxt)
    a.L('range_done');ui.row();ui.frequency(n.SCAN_LOW,False);ui.text('-');ui.frequency(n.SCAN_HIGH,False);ui.flush(2)
    ui.clear();ui.text('2 MIN C/N:');ui.get(n.SCAN_THRESHOLD);ui.pointer('thresholds');a.emit(0x93,0xFA);a.movri(3,0);ui.number_regs();ui.text('DB')
    ui.row();ui.text('3 PAUSE:');ui.get(n.SCAN_DWELL);ui.pointer('dwells');a.emit(0x93,0xFA);a.movri(3,0);ui.number_regs();ui.text('S 4:')
    ui.get(n.SCAN_DIRECTION);a.jz('direction_down');ui.text('UP');a.sjmp('direction_done');a.L('direction_down');ui.text('DOWN');a.L('direction_done');ui.flush(4)
    ui.clear();ui.text('5 RUN/PAUSE 6 NEXT');ui.row();ui.text('0 EXIT 7 RESET 8 MENU');ui.flush(6)
    ui.tables['thresholds']=bytes(THRESHOLDS);ui.tables['dwells']=bytes([2,5,10])
    return ui.finish()
